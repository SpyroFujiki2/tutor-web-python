def list_messages(session: Session, user_id: UUID, booking_id: UUID, dispute_id: UUID | None=None, *, limit: int=50, offset: int=0, before_id: int | None=None) -> list[Message]:
    require(1 <= limit <= 100 and offset >= 0, "Phân trang không hợp lệ")
    if dispute_id:
        dispute = dispute_access(session, user_id, dispute_id)
        require(dispute.booking_id == booking_id, "Tranh chấp không thuộc đơn", LookupError)
    else:
        accessible_booking(session, user_id, booking_id)
    statement = select(Message).where(Message.booking_id == booking_id, Message.dispute_id == dispute_id)
    if before_id is not None:
        pivot = session.scalar(statement.where(Message.id == before_id))
        require(pivot is not None, "Không tìm thấy mốc tin nhắn", LookupError)
        statement = statement.where(or_(Message.created_at < pivot.created_at,
                                        and_(Message.created_at == pivot.created_at, Message.id < pivot.id)))
    return list(session.scalars(statement.order_by(Message.created_at.desc(), Message.id.desc()).offset(offset).limit(limit)))


def check_message_permission(session: Session, user_id: UUID, booking_id: UUID, dispute_id: UUID | None=None, *, lock: bool=True) -> None:
    if dispute_id:
        actor(session, user_id)
        get(session, Booking, booking_id, lock=lock)
        dispute = dispute_access(session, user_id, dispute_id)
        require(dispute.booking_id == booking_id and not dispute.is_completed, "Tranh chấp không hoạt động")
    else:
        booking = accessible_booking(session, user_id, booking_id, lock=lock)
        require(booking.status not in {BookingStatus.CANCELLED, BookingStatus.REFUNDED}, "Đơn đã đóng")
    recent = session.scalar(select(func.count()).select_from(Message).where(
        Message.booking_id == booking_id, Message.sender_id == user_id,
        Message.created_at > now() - timedelta(minutes=1)))
    require(recent < 30, "Bạn gửi tin nhắn quá nhanh; hãy chờ một phút", RateLimitError)


def send_message(session: Session, user_id: UUID, booking_id: UUID, content: str, dispute_id: UUID | None=None) -> Message:
    require(content.strip() and len(content) <= 5000, "Nội dung không hợp lệ")
    check_message_permission(session, user_id, booking_id, dispute_id)
    return add(session, Message, booking_id=booking_id, sender_id=user_id, dispute_id=dispute_id,
               content=content.strip(), created_at=now())


def send_file_message(session: Session, user_id: UUID, booking_id: UUID, file_url: str, filename: str, dispute_id: UUID | None=None) -> Message:
    """file_url must be generated by the local attachment store, never a client URL."""
    require(bool(re.fullmatch(r'/api/bookings/' + str(booking_id)
            + r'/attachments/[0-9a-f-]{36}\.(pdf|png|jpg|txt)', file_url)), "Đường dẫn tệp không hợp lệ")
    require(0 < len(filename.strip()) <= 120, "Tên tệp không hợp lệ")
    check_message_permission(session, user_id, booking_id, dispute_id)
    return add(session, Message, booking_id=booking_id, sender_id=user_id, dispute_id=dispute_id,
               file_url=file_url, content=filename.strip(), created_at=now())
